/** Refresh pinned font preference data and the synchronous Unicode lookup used in VCL callbacks. */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const entry = new URL('../packages/entry/', import.meta.url);
const require = createRequire(new URL('package.json', entry));
const chromium = 'https://raw.githubusercontent.com/chromium/chromium/ffaf825e8c2e27fccc089b425f9f114d275804ae/third_party/blink/renderer/platform/fonts/win/font_fallback_win.cc';
const fontconfig = 'https://raw.githubusercontent.com/fontconfig/fontconfig/84ae86bc21c94d4aedbc02e32c9dc18b8750193c/';
async function read(url) { const response = await fetch(url); if (!response.ok) throw new Error(`${url}: ${response.status}`); return response.text(); }
const [chrome, config, license] = await Promise.all([read(chromium), read(`${fontconfig}conf.d/65-nonlatin.conf`), read(`${fontconfig}COPYING`)]);
const arrays = new Map([...chrome.matchAll(/static const char\* const (k\w+Fonts)\[\] = \{([^}]+)\}/g)]
  .map(([, name, values]) => [name, [...values.matchAll(/"([^"]+)"/g)].map(match => match[1])]));
const windows = Object.fromEntries([...chrome.matchAll(/\{USCRIPT_(\w+),\s*(k\w+Fonts)\}/g)]
  .map(([, script, name]) => [script.toLowerCase(), arrays.get(name)]));
const generic = Object.fromEntries([...config.matchAll(/<alias>\s*<family>([^<]+)<\/family>\s*<prefer>([\s\S]*?)<\/prefer>/g)]
  .map(([, name, values]) => [name, [...values.matchAll(/<family>([^<]+)<\/family>/g)].map(match => match[1])]));
const properties = (await import(pathToFileURL(require.resolve('@unicode/unicode-17.0.0')))).default;
const names = properties.Script;
const ranges = [];
const common = [];
for (const [index, name] of names.entries()) {
  const { default: values } = await import(pathToFileURL(require.resolve(`@unicode/unicode-17.0.0/Script/${name}/ranges.mjs`)));
  for (const range of values) { ranges.push([range.begin, range.end, index]); if (name === 'Common' || name === 'Inherited') common.push(range); }
}
ranges.sort((a, b) => a[0] - b[0]);
const extensions = [];
for (const [index, name] of names.entries()) {
  if (name === 'Common' || name === 'Inherited') continue;
  const { default: values } = await import(pathToFileURL(require.resolve(`@unicode/unicode-17.0.0/Script_Extensions/${name}/ranges.mjs`)));
  for (const a of values) for (const b of common) {
    const first = Math.max(a.begin, b.begin), end = Math.min(a.end, b.end);
    if (first < end) extensions.push([first, end, index]);
  }
}
const header = `/** Generated by scripts/generate-font-preferences.mjs; do not edit.\n+ * Chromium: ${chromium}\n+ * Fontconfig: ${fontconfig}conf.d/65-nonlatin.conf\n+ * Unicode: @unicode/unicode-17.0.0 2.0.7. Licenses: packages/entry/NOTICE.\n+ */\n`;
const declarations = [
  ['WINDOWS_FONTS', windows, 'Readonly<Record<string, readonly string[]>>'],
  ['FONTCONFIG_FONTS', generic, 'Readonly<Record<string, readonly string[]>>'],
  ['SCRIPT_NAMES', names, 'readonly string[]'],
  ['SCRIPT_RANGES', ranges, 'readonly (readonly [number, number, number])[]'],
  ['SCRIPT_EXTENSIONS', extensions, 'readonly (readonly [number, number, number])[]'],
].map(([name, value, type]) => `/** Pinned ${name.toLowerCase().replaceAll('_', ' ')}. */\nexport const ${name}: ${type} = ${name.startsWith('SCRIPT_') ? `JSON.parse(${JSON.stringify(JSON.stringify(value))})` : JSON.stringify(value)}\n`);
writeFileSync(new URL('src/font-preferences-data.ts', entry), header + declarations.join('\n'));
const noticePath = new URL('NOTICE', entry);
const marker = '\nFont preference data\n';
const notice = readFileSync(noticePath, 'utf8').split(marker)[0];
writeFileSync(noticePath, notice + marker + `\n${chromium}\n${chrome.slice(0, chrome.indexOf('*/') + 2)}\n\n${fontconfig}COPYING\n${license.trim()}\n\nUnicode data is supplied by @unicode/unicode-17.0.0 under its included MIT license.\n`);
console.log(`Generated ${Object.keys(windows).length} script preferences and ${ranges.length} Unicode ranges in ${fileURLToPath(entry)}`);
